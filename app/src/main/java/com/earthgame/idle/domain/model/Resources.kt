val RESOURCE_LIST: List<ResourceDefinition> = ResourceId.entries.map { RESOURCES.getValue(it) }

fun resourceOf(id: ResourceId): ResourceDefinition = RESOURCES.getValue(id)

/** Resources of one class, in enum order. The Production screen's grouping. */
fun resourcesOfClass(resourceClass: ResourceClass): List<ResourceDefinition> =
    RESOURCE_LIST.filter { it.resourceClass == resourceClass }
