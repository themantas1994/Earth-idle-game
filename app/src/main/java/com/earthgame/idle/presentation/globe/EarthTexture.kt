/**
 * The Earth's surface, generated in code.
 *
 * ## Why it is generated rather than shipped
 *
 * An Earth texture is exactly the kind of asset whose licensing quietly goes
 * unrecorded — the repository already carries one such problem (see
 * `docs/ASSETS.md`) and this feature was not going to add another. Every pixel
 * the globe draws is computed here from data authored in this file, so the
 * artwork is unambiguously this project's own, there is no attribution to
 * carry, and the APK grows by a few kilobytes of Kotlin instead of a few
 * megabytes of PNG.
 *
 * ## What is authored and what is generated
 *
 * [CONTINENTS] is hand-authored: coarse outlines of the landmasses in degrees
 * of longitude and latitude, written for this project, accurate enough that the
 * planet reads as Earth at a glance and no more precise than that. Everything
 * else — coastline detail, terrain, ice, ocean depth, cloud cover — is
 * generated by blurring that outline and perturbing it with value noise.
 *
 * The result is deliberately a **stylised** Earth rather than a photographic
 * one, which is both the look the rest of the game has and the only honest
 * thing to claim for an outline this coarse.
 *
 * Generation costs tens of milliseconds and happens once, off the main thread —
 * see `GlobeSurface`.
 */
