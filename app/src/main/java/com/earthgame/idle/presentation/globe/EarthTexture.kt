    /**
     * The land/sea field the texture is painted from, at [TEXTURE_WIDTH] ×
     * [TEXTURE_HEIGHT].
     *
     * Values above 0.5 are land; how far above sets how far inland. Built by
     * rasterising [CONTINENTS] coarsely, blurring the result (wrapping in
     * longitude so the seam is invisible) and roughening the coastline with
     * fractal noise, which is what turns straight authored edges into something
     * that reads as a coast.
     */
    private fun buildLandField(width: Int, height: Int): FloatArray {
        val coarse = rasteriseContinents()
        val blurred = blurWrapping(coarse, MASK_WIDTH, MASK_HEIGHT, radius = 2)

        val field = FloatArray(width * height)
        for (y in 0 until height) {
            val v = (y + 0.5f) / height
            for (x in 0 until width) {
                val u = (x + 0.5f) / width
                val base = sampleBilinearWrapping(blurred, MASK_WIDTH, MASK_HEIGHT, u, v)
                // Coastline roughness. The noise is sampled at the texture's own
                // scale so the detail is finer than anything the outlines carry.
                val roughness = fractalNoise(u * 14f, v * 7f, seed = 1, octaves = 4, periodX = 14)
                field[y * width + x] = base + 0.34f * (roughness - 0.5f) * 2f
            }
        }
        return field
    }

    /** Point-in-polygon rasterisation of the authored outlines, with bounding-box culling. */
    private fun rasteriseContinents(): FloatArray {
        val bounds = CONTINENTS.map { ring ->
            var minLon = 180.0
            var maxLon = -180.0
            var minLat = 90.0
            var maxLat = -90.0
            for ((lon, lat) in ring) {
                minLon = min(minLon, lon); maxLon = max(maxLon, lon)
                minLat = min(minLat, lat); maxLat = max(maxLat, lat)
            }
            doubleArrayOf(minLon, maxLon, minLat, maxLat)
        }

        val mask = FloatArray(MASK_WIDTH * MASK_HEIGHT)
        for (y in 0 until MASK_HEIGHT) {
            val latitude = 90.0 - (y + 0.5) * 180.0 / MASK_HEIGHT
            for (x in 0 until MASK_WIDTH) {
                val longitude = -180.0 + (x + 0.5) * 360.0 / MASK_WIDTH
                var land = false
                for (index in CONTINENTS.indices) {
                    val box = bounds[index]
                    if (longitude < box[0] || longitude > box[1]) continue
                    if (latitude < box[2] || latitude > box[3]) continue
                    if (containsPoint(CONTINENTS[index], longitude, latitude)) {
                        land = true
                        break
                    }
                }
                if (land) mask[y * MASK_WIDTH + x] = 1f
            }
        }
        return mask
    }

    /** Standard even-odd crossing test on a closed ring. */
    private fun containsPoint(ring: List<Pair<Double, Double>>, x: Double, y: Double): Boolean {
        var inside = false
        var j = ring.size - 1
        for (i in ring.indices) {
            val (xi, yi) = ring[i]
            val (xj, yj) = ring[j]
            if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) {
                inside = !inside
            }
            j = i
        }
        return inside
    }

    /** Separable box blur. Longitude wraps; latitude clamps. */
    private fun blurWrapping(source: FloatArray, width: Int, height: Int, radius: Int): FloatArray {
        val horizontal = FloatArray(source.size)
        val window = radius * 2 + 1
        for (y in 0 until height) {
            for (x in 0 until width) {
                var total = 0f
                for (offset in -radius..radius) {
                    val sx = ((x + offset) % width + width) % width
                    total += source[y * width + sx]
                }
                horizontal[y * width + x] = total / window
            }
        }
        val result = FloatArray(source.size)
        for (y in 0 until height) {
            for (x in 0 until width) {
                var total = 0f
                for (offset in -radius..radius) {
                    val sy = (y + offset).coerceIn(0, height - 1)
                    total += horizontal[sy * width + x]
                }
                result[y * width + x] = total / window
            }
        }
        return result
    }

    private fun sampleBilinearWrapping(
        source: FloatArray,
        width: Int,
        height: Int,
        u: Float,
        v: Float,
    ): Float {
        val fx = u * width - 0.5f
        val fy = (v * height - 0.5f).coerceIn(0f, height - 1.0001f)
        val x0 = kotlin.math.floor(fx).toInt()
        val y0 = kotlin.math.floor(fy).toInt()
        val tx = fx - x0
        val ty = fy - y0
        val x0w = ((x0 % width) + width) % width
        val x1w = (x0w + 1) % width
        val y0c = y0.coerceIn(0, height - 1)
        val y1c = (y0 + 1).coerceIn(0, height - 1)

        val a = source[y0c * width + x0w]
        val b = source[y0c * width + x1w]
        val c = source[y1c * width + x0w]
        val d = source[y1c * width + x1w]
        return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty
    }

