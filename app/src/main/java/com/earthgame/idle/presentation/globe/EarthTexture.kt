    /**
     * The Earth's colour map.
     *
     * The palette is chosen to sit with the rest of the game's UI rather than
     * to match satellite imagery: saturated ocean, readable biome bands by
     * latitude, brightened relief, and ice that reaches down from both poles.
     */
    fun createEarthBitmap(
        width: Int = TEXTURE_WIDTH,
        height: Int = TEXTURE_HEIGHT,
    ): Bitmap {
        val field = buildLandField(width, height)
        val pixels = IntArray(width * height)

        for (y in 0 until height) {
            val v = (y + 0.5f) / height
            val latitude = 90f - v * 180f
            val absLatitude = abs(latitude)
            for (x in 0 until width) {
                val u = (x + 0.5f) / width
                val index = y * width + x
                val landness = field[index]

                pixels[index] = if (landness > 0.5f) {
                    val inland = ((landness - 0.5f) / 0.5f).coerceIn(0f, 1f)
                    val relief = fractalNoise(u * 26f, v * 13f, seed = 7, octaves = 4, periodX = 26)
                    landColour(absLatitude, inland, relief)
                } else {
                    val depth = ((0.5f - landness) / 0.5f).coerceIn(0f, 1f)
                    oceanColour(absLatitude, depth)
                }
            }
        }
        return Bitmap.createBitmap(pixels, width, height, Bitmap.Config.ARGB_8888)
    }

    private fun landColour(absLatitude: Float, inland: Float, relief: Float): Int {
        // Biome bands by latitude: rainforest, desert, temperate, boreal, tundra.
        val tropical = intArrayOf(0x2F, 0x7A, 0x3C)
        val arid = intArrayOf(0xC2, 0xA0, 0x5E)
        val temperate = intArrayOf(0x4A, 0x7C, 0x45)
        val boreal = intArrayOf(0x35, 0x5E, 0x45)
        val tundra = intArrayOf(0x8C, 0x93, 0x86)

        val base = when {
            absLatitude < 12f -> tropical
            absLatitude < 20f -> blend(tropical, arid, (absLatitude - 12f) / 8f)
            absLatitude < 32f -> arid
            absLatitude < 42f -> blend(arid, temperate, (absLatitude - 32f) / 10f)
            absLatitude < 54f -> temperate
            absLatitude < 64f -> blend(temperate, boreal, (absLatitude - 54f) / 10f)
            absLatitude < 70f -> blend(boreal, tundra, (absLatitude - 64f) / 6f)
            else -> tundra
        }

        // Relief lightens high ground and darkens basins, and drier interiors
        // pale off — enough shape that the land is not a flat wash.
        val shade = 0.82f + 0.36f * relief + 0.10f * inland
        var r = (base[0] * shade)
        var g = (base[1] * shade)
        var b = (base[2] * shade)

        // Permanent ice, reaching further at the poles.
        val ice = ((absLatitude - 66f) / 14f).coerceIn(0f, 1f)
        if (ice > 0f) {
            r = r * (1 - ice) + 0xF0 * ice
            g = g * (1 - ice) + 0xF6 * ice
            b = b * (1 - ice) + 0xFF * ice
        }
        return argb(r, g, b)
    }

    private fun oceanColour(absLatitude: Float, depth: Float): Int {
        val shallow = intArrayOf(0x2E, 0x86, 0xA8)
        val deep = intArrayOf(0x0B, 0x2C, 0x59)
        val base = blend(shallow, deep, smoothstep(depth))

        var r = base[0].toFloat()
        var g = base[1].toFloat()
        var b = base[2].toFloat()

        // Sea ice over the polar oceans.
        val ice = ((absLatitude - 72f) / 12f).coerceIn(0f, 1f)
        if (ice > 0f) {
            r = r * (1 - ice) + 0xDF * ice
            g = g * (1 - ice) + 0xEC * ice
            b = b * (1 - ice) + 0xF7 * ice
        }
        return argb(r, g, b)
    }

    /**
     * The cloud shell's alpha map.
     *
     * Banded by latitude to match the wind model's three cells — a wet band
     * over the equator, clear subtropics, a stormy mid-latitude belt — so the
     * clouds and the wind streamlines tell the same story. Fully transparent
     * where there is no cloud, so one texture serves every cloud coverage: the
     * shader scales its opacity by the simulated humidity rather than the
     * texture being regenerated.
     */
    fun createCloudBitmap(width: Int = 512, height: Int = 256): Bitmap {
        val pixels = IntArray(width * height)
        for (y in 0 until height) {
            val v = (y + 0.5f) / height
            val absLatitude = abs(90f - v * 180f)
            val band = when {
                absLatitude < 10f -> 1.0f
                absLatitude < 22f -> 1.0f - (absLatitude - 10f) / 12f * 0.75f
                absLatitude < 32f -> 0.25f
                absLatitude < 60f -> 0.25f + (absLatitude - 32f) / 28f * 0.7f
                else -> 0.95f - (absLatitude - 60f) / 30f * 0.35f
            }
            for (x in 0 until width) {
                val u = (x + 0.5f) / width
                val noise = fractalNoise(u * 10f, v * 5f, seed = 23, octaves = 5, periodX = 10)
                val density = ((noise - 0.42f) / 0.45f).coerceIn(0f, 1f) * band
                val alpha = (density * 255f).toInt().coerceIn(0, 255)
                pixels[y * width + x] = (alpha shl 24) or 0x00FFFFFF
            }
        }
        return Bitmap.createBitmap(pixels, width, height, Bitmap.Config.ARGB_8888)
    }

    // ---------------------------------------------------------------- noise --

    /**
     * Value noise, tiling in x so the texture has no seam at the date line.
     *
     * Value rather than gradient noise on purpose: it is a handful of integer
     * operations per sample, it is perfectly reproducible across devices
     * because nothing in it depends on a platform RNG, and at the scales used
     * here the difference is invisible.
     */
    private fun fractalNoise(x: Float, y: Float, seed: Int, octaves: Int, periodX: Int): Float {
        var total = 0f
        var amplitude = 1f
        var normaliser = 0f
        var frequency = 1f
        var period = periodX
        for (octave in 0 until octaves) {
            total += amplitude * valueNoise(x * frequency, y * frequency, seed + octave, period)
            normaliser += amplitude
            amplitude *= 0.5f
            frequency *= 2f
            period *= 2
        }
        return total / normaliser
    }

    private fun valueNoise(x: Float, y: Float, seed: Int, periodX: Int): Float {
        val x0 = kotlin.math.floor(x).toInt()
        val y0 = kotlin.math.floor(y).toInt()
        val tx = smoothstep(x - x0)
        val ty = smoothstep(y - y0)

        val a = hash(wrap(x0, periodX), y0, seed)
        val b = hash(wrap(x0 + 1, periodX), y0, seed)
        val c = hash(wrap(x0, periodX), y0 + 1, seed)
        val d = hash(wrap(x0 + 1, periodX), y0 + 1, seed)

        return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty
    }

    private fun wrap(value: Int, period: Int): Int = ((value % period) + period) % period

    private fun hash(x: Int, y: Int, seed: Int): Float {
        var h = x * 374761393 + y * 668265263 + seed * 1274126177
        h = (h xor (h shr 13)) * 1274126177
        h = h xor (h shr 16)
        return (h and 0x7FFFFFF).toFloat() / 0x7FFFFFF.toFloat()
    }

    private fun smoothstep(x: Float): Float {
        val t = x.coerceIn(0f, 1f)
        return t * t * (3f - 2f * t)
    }

    private fun blend(a: IntArray, b: IntArray, t: Float): IntArray {
        val k = t.coerceIn(0f, 1f)
        return intArrayOf(
            (a[0] + (b[0] - a[0]) * k).toInt(),
            (a[1] + (b[1] - a[1]) * k).toInt(),
            (a[2] + (b[2] - a[2]) * k).toInt(),
        )
    }

    private fun argb(r: Float, g: Float, b: Float): Int =
        (0xFF shl 24) or
            (r.toInt().coerceIn(0, 255) shl 16) or
            (g.toInt().coerceIn(0, 255) shl 8) or
            b.toInt().coerceIn(0, 255)
}
